// Writes src/font-licenses.ts: the full license text of each font the app
// embeds, as its package ships it, so the app carries the notices the SIL Open
// Font License asks to travel with the fonts and Settings can show them. Run it
// after changing a font package: `node apps/mobile/scripts/font-licenses.ts`. A
// unit test fails when the module and the packages differ.

import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

export const APP_DIR = join(import.meta.dirname, "..");

/** The embedded fonts' packages, and the name Settings gives each. */
export const FONT_PACKAGES = [
  { name: "Figtree", pkg: "@expo-google-fonts/figtree" },
  { name: "JetBrains Mono", pkg: "@expo-google-fonts/jetbrains-mono" },
] as const;

export function licenseText(pkg: string): string {
  return readFileSync(join(APP_DIR, "node_modules", pkg, "LICENSE_FONT"), "utf8");
}

export function moduleSource(): string {
  const entries = FONT_PACKAGES.map(
    ({ name, pkg }) =>
      `  { name: ${JSON.stringify(name)}, text: ${JSON.stringify(licenseText(pkg))} },`,
  );
  return `// Generated by scripts/font-licenses.ts from the font packages' LICENSE_FONT files. Do not edit.

/** The license of each font this app embeds, whole. */
export const FONT_LICENSES: ReadonlyArray<{ name: string; text: string }> = [
${entries.join("\n")}
];
`;
}

if (process.argv[1] === import.meta.filename) {
  writeFileSync(join(APP_DIR, "src/font-licenses.ts"), moduleSource());
  console.log("Wrote src/font-licenses.ts");
}
